const assert = require('node:assert/strict');
const path = require('node:path');

module.exports = async ({page,rpc,control,text,shot,check,requests}) => {
  const pane = page.locator('#view-workspace');
  const detail = page.locator('#ws-detail');
  const rows = page.locator('#ws-list .ws-row');
  const open = async target => {
    const link=page.locator(`[data-target=${target}]`);
    if (!await link.isVisible()) await page.locator('#nav-toggle').click();
    await link.click();
  };
  const choose = async goal => { await rows.filter({hasText:goal}).click(); };
  const state = async (goal,label) => rows.filter({hasText:goal}).locator('.ws-state').filter({hasText:label}).waitFor();
  const task = async goal => (await rpc('get_roster')).tasks.find(row=>row.goal===goal);
  const assign = async (goal,manual) => {
    await pane.getByRole('button',{name:'New assignment'}).click();
    assert.equal(await page.evaluate(()=>document.activeElement.id),'ws-goal');
    await pane.getByLabel('What should the worker do?').fill(goal);
    await pane.getByLabel('Task worker').selectOption('research');
    await pane.getByLabel('Review policy').selectOption(manual?'manual':'automatic');
    await pane.getByRole('button',{name:'Assign task',exact:true}).click();
    await text('#ws-status',/Assignment saved/);
    await text('#ws-summary',goal);
  };
  const noReview = async () => assert.equal(await detail.locator('[data-ws-action=approve],[data-ws-action=reject]').count(),0);
  const reviewProbe = (id,verdict,attempt) => page.evaluate(([id,verdict,attempt])=>window.pywebview.api.review_task(id,verdict,attempt),[id,verdict,attempt]);
  const manual = 'Compare workshop options';
  const automatic = 'Summarize the project notes';
  const retried = 'Draft a handoff summary';
  const failure = 'Fail a controlled execution';

  await page.getByRole('textbox',{name:'Message FRIDAY'}).fill('Keep this chat draft');
  await open('view-workspace');
  await text('#ws-list',/No tasks recorded/);
  assert.equal(await page.getByRole('textbox',{name:'Message FRIDAY'}).inputValue(),'Keep this chat draft');
  await assign(manual,true);
  await state(manual,'Running');
  await noReview();
  const a=await task(manual);
  assert.equal(a.state,'running');
  assert.equal((await reviewProbe(a.id,'approve',a.attempt)).ok,false);
  await assign(automatic,false);
  await state(automatic,'Queued');
  await noReview();
  assert.equal((await task(automatic)).state,'queued');
  await control('workspace:release',{goal:manual});
  await state(automatic,'Running');
  await state(manual,'Awaiting review');
  await choose(manual);
  await text('#ws-summary',/fixture-provider \/ fixture-executor/);
  await detail.getByRole('button',{name:'Read result'}).click();
  await text('#ws-artifact-content',`Persisted output for ${manual}`);
  assert.match(await page.locator('#ws-artifact-content').innerText(),/<em>Literal result text<\/em>/);
  assert.equal(await page.locator('#ws-artifact-content em').count(),0);
  await shot('18-workspace-desktop');
  const reviewCount=requests.filter(item=>item.method==='review_task').length;
  await detail.getByRole('button',{name:'Approve result'}).click();
  await state(manual,'Approved');
  await noReview();
  assert.deepEqual(requests.filter(item=>item.method==='review_task').slice(reviewCount).map(item=>item.args),[[a.id,'approve',a.attempt]]);
  assert.equal((await reviewProbe(a.id,'approve',a.attempt)).ok,false);
  await control('workspace:release',{goal:automatic});
  await state(automatic,'Result saved');
  await choose(automatic);
  await noReview();
  await text('#ws-summary',/No manual decision was recorded/);
  await detail.getByRole('button',{name:'Read result'}).click();
  await text('#ws-artifact-content',`Persisted output for ${automatic}`);
  assert.doesNotMatch(await page.locator('#ws-artifact-content').innerText(),new RegExp(manual));
  check('Explicit assignments use real queue/running/completion; early and duplicate review are refused; automatic and manual outcomes differ');

  await assign(retried,true);
  await state(retried,'Running');
  const first=await task(retried);
  await detail.getByRole('button',{name:'Cancel attempt'}).click();
  await state(retried,'Cancelled');
  await noReview();
  await control('workspace:release',{goal:retried});
  // Reopen is an explicit fixture synchronization and persists the cancelled record.
  await control('workspace:reopen');
  await detail.getByRole('button',{name:'Retry task'}).click();
  await state(retried,'Running');
  const second=await task(retried);
  assert.notEqual(second.attempt,first.attempt);
  assert.equal((await rpc('world_command',['cancel_execution',{task_id:second.id,attempt:first.attempt}])).ok,false);
  await control('workspace:release',{goal:retried});
  await state(retried,'Awaiting review');
  assert.equal((await reviewProbe(second.id,'approve',first.attempt)).ok,false);
  assert.equal((await reviewProbe(second.id,'approve',a.attempt)).ok,false);
  assert.equal((await reviewProbe(second.id,'approve',null)).ok,false);
  assert.equal((await task(retried)).state,'awaiting_review');
  await detail.getByRole('button',{name:'Reject result'}).click();
  await state(retried,'Rejected');
  await text('#ws-history',/Attempt 1[\s\S]*Cancelled/);
  await noReview();
  await assign(failure,false);
  await state(failure,'Failed');
  await text('#ws-summary',/Synthetic executor failure/);
  await text('#ws-summary',/Executor not recorded/);
  check('Cancel and Retry preserve old attempts; stale, cross-task and missing review tokens cannot review the retry; failures stay distinct');

  await pane.getByLabel('Search tasks').fill('project notes');
  assert.equal(await rows.count(),1);
  await text('#ws-summary',automatic);
  await detail.getByRole('button',{name:'Read result'}).click();
  await text('#ws-artifact-content',`Persisted output for ${automatic}`);
  await pane.getByLabel('Search tasks').fill('no fixture task');
  await text('#ws-list',/No tasks match/);
  assert.ok(await page.locator('#ws-artifact-content').isHidden());
  await pane.getByLabel('Search tasks').fill('');
  await pane.getByLabel('State').selectOption('failed');
  assert.equal(await rows.count(),1);
  await text('#ws-summary',failure);
  await pane.getByLabel('State').selectOption('');
  await choose(manual);
  await rows.filter({hasText:manual}).press('End');
  assert.equal(await rows.last().getAttribute('aria-pressed'),'true');
  assert.equal(await page.evaluate(()=>document.activeElement.classList.contains('ws-row')),true);
  assert.notEqual(await rows.last().evaluate(el=>getComputedStyle(el).outlineStyle),'none');
  await choose(retried);
  await detail.getByRole('button',{name:'Read result'}).click();
  await text('#ws-artifact-content',`Persisted output for ${retried}`);
  assert.equal(await detail.getByRole('button',{name:'Read result'}).count(),1);
  await detail.getByText('Ownership & diagnostics').click();
  await text('#ws-diagnostics',/no explicit catalog mapping/);
  check('Search, persisted-state filtering and keyboard focus preserve task-specific artifact selection and typed ownership');

  await control('workspace:artifact',{task_id:a.id,state:'revoked'});
  await control('workspace:artifact',{task_id:(await task(automatic)).id,state:'missing'});
  await control('workspace:artifact',{task_id:(await task(failure)).id,state:'error'});
  await control('workspace:reopen');
  await page.reload();
  await open('view-workspace');
  await state(manual,'Approved');
  await choose(manual);
  await text('#ws-artifacts',/Revoked/);
  assert.equal(await detail.getByRole('button',{name:'Read result'}).count(),0);
  await choose(automatic);
  await text('#ws-artifacts',/File missing/);
  assert.equal(await detail.getByRole('button',{name:'Read result'}).count(),0);
  await choose(failure);
  await text('#ws-artifacts',/Artifact error/);
  await text('#ws-artifacts',/Synthetic artifact error/);
  assert.equal(await detail.getByRole('button',{name:'Read result'}).count(),0);
  await choose(retried);
  await text('#ws-history',/Attempt 1[\s\S]*Cancelled/);
  await detail.getByRole('button',{name:'Read result'}).click();
  await text('#ws-artifact-content',`Persisted output for ${retried}`);
  check('Real store reopen and page reload retain outcomes, attempt history, artifact content, errors, missing files and revocation');

  await page.setViewportSize({width:760,height:700});
  await shot('19-workspace-compact');
  await pane.getByRole('button',{name:/View selected task/}).click();
  assert.equal(await page.evaluate(()=>document.activeElement.id),'ws-detail');
  await page.screenshot({path:path.join(__dirname,'screenshots/20-workspace-compact-detail.png')});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.setViewportSize({width:390,height:844});
  await shot('21-workspace-narrow');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await control('workspace:read-error',{value:true});
  await text('#ws-status',/could not be read/);
  await noReview();
  assert.ok(await page.locator('#ws-artifact-content').isHidden());
  await control('workspace:read-error',{value:false});
  await state(manual,'Approved');
  assert.ok(!requests.some(item=>['get_world','get_lab','get_identity_views'].includes(item.method)));
  check('Desktop, compact and narrow Workspace render; unavailable read disables actions and recovers without simulation or identity reads');
};
