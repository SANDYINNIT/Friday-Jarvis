const assert=require('node:assert/strict');
module.exports=async({page,rpc,text,shot,check,hold})=>{
  const nav=async target=>{const b=page.locator(`[data-target=${target}]`);if(!await b.isVisible()&&await page.locator('#nav-toggle').isVisible())await page.locator('#nav-toggle').click();await b.evaluate(el=>el.closest('details')&&(el.closest('details').open=true));await b.click();};
  const input=page.getByRole('textbox',{name:'Message FRIDAY'});
  await input.fill('Keep the live composer draft');
  await nav('view-tasks');
  await page.getByRole('button',{name:'New personal task',exact:true}).click();
  let form=page.locator('#personal-task-editor');
  await form.getByLabel('Title',{exact:true}).fill('A deliberate local task');
  await form.getByLabel('Notes',{exact:true}).fill('Persist this note');
  await form.getByRole('button',{name:'Save',exact:true}).click();
  await form.waitFor({state:'hidden'});
  await text('#planner-task-list',/A deliberate local task/);
  const task=(await rpc('get_tasks')).tasks.find(r=>r.title==='A deliberate local task');
  assert.ok(task?.revision);
  await page.locator(`[data-planner-key="personal:${task.id}"]`).click();
  await page.getByRole('button',{name:'Complete / reopen',exact:true}).click();
  await text('#planner-task-summary',/Completed|Done|done/);
  assert.equal((await rpc('get_tasks')).tasks.find(r=>r.id===task.id).status,'done');
  await page.getByRole('button',{name:'Edit personal task',exact:true}).click();
  await form.getByLabel('Title',{exact:true}).fill('Retain my unsaved edit');
  const current=(await rpc('get_tasks')).tasks.find(r=>r.id===task.id);
  assert.ok((await rpc('mutate_personal_task',['task-'+task.id,'update',{title:'A newer saved task'},current.revision])).ok);
  await form.getByRole('button',{name:'Save',exact:true}).click();
  await page.getByText('This personal task changed. Refresh before saving.',{exact:true}).waitFor();
  assert.equal(await form.getByLabel('Title',{exact:true}).inputValue(),'Retain my unsaved edit');
  await form.getByRole('button',{name:'Cancel',exact:true}).click();
  if(process.argv.includes('--pretest-interleaving')) {
    const second=await rpc('mutate_personal_task',[null,'create',{title:'Keep second task separate'},null,false,'ab'.repeat(16)]);
    const secondId=second.task.id;
    await text('#planner-task-list',/Keep second task separate/);
    await page.locator(`[data-planner-key="personal:${task.id}"]`).click();
    await page.getByRole('button',{name:'Edit personal task',exact:true}).click();
    await form.getByLabel('Title',{exact:true}).fill('Bound to the first task');
    const pending=hold('mutate_personal_task');
    await form.getByRole('button',{name:'Save',exact:true}).click();await pending.received;
    await page.locator(`[data-planner-key="personal:${secondId}"]`).click();
    await page.getByRole('button',{name:'Complete / reopen',exact:true}).click();
    pending.release();
    await page.waitForFunction(()=>!document.querySelector('#personal-task-editor [name=title]').disabled);
    if(await form.isVisible())await form.getByRole('button',{name:'Save',exact:true}).click();
    await form.waitFor({state:'hidden'});
    const rows=(await rpc('get_tasks')).tasks;
    assert.equal(rows.find(r=>r.id===secondId).title,'Keep second task separate','Pending editor was retargeted to another task');
    assert.equal(rows.find(r=>r.id===secondId).status,'open');
    const first=rows.find(r=>r.id===task.id);
    assert.ok((await rpc('mutate_personal_task',['task-'+task.id,'update',{title:'A newer saved task'},first.revision])).ok);
    check('A pending edit cannot be retargeted by another selected task action');
  }
  await shot('completion-personal-tasks-desktop');
  check('Personal task create and completion persist through exact typed bridge paths');
  await nav('view-calendar');
  await page.getByRole('button',{name:'New local event',exact:true}).click();
  form=page.locator('#personal-event-editor');
  await form.getByLabel('Title',{exact:true}).fill('A local agenda entry');
  await form.getByLabel('Start',{exact:true}).fill('2026-11-14T10:00+01:00');
  await form.getByLabel('Duration in minutes').fill('90');
  await form.getByRole('button',{name:'Save',exact:true}).click();
  await form.waitFor({state:'hidden'});
  const agenda=await rpc('get_schedule');
  assert.equal(agenda.events.find(e=>e.title==='A local agenda entry').duration_minutes,90);
  await page.getByLabel('Agenda date').fill('2026-11-14');
  await page.getByLabel('Agenda date').dispatchEvent('change');
  await text('#agenda-list',/A local agenda entry/);
  await shot('completion-calendar-desktop');
  check('Local calendar creation uses acknowledged persisted timezone-aware events');
  await nav('view-conversations');
  await text('#conversations-library-list',/Saved synthetic question/);
  await page.locator('#conversations-library-list button').first().click();
  await text('#conversations-library-record',/Saved synthetic answer/);
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export displayed transcript'}).click();
  assert.equal((await download).suggestedFilename(),'friday-conversation.json');
  const ref=(await rpc('get_conversation_library')).rows[0].id;
  const output=await rpc('export_conversation',[ref]);assert.ok(output.ok);
  await page.setViewportSize({width:760,height:650});
  await page.locator('#conversations-library-detail').scrollIntoViewIfNeeded();
  await shot('completion-conversations-compact',false);
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'Delete saved conversation',exact:true}).click();
  await text('#conversations-library-list',/No matching|No saved|No conversations|No records/);
  assert.equal((await rpc('get_conversation_library')).rows.length,0);
  await page.reload();await nav('view-tasks');await text('#planner-task-list',/A newer saved task/);
  assert.equal((await rpc('get_tasks')).tasks.find(r=>r.id===task.id).status,'done');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'New personal task',exact:true}).click();
  const draft=page.locator('#personal-task-editor');await draft.getByLabel('Title',{exact:true}).fill('Unsaved local draft');
  await draft.scrollIntoViewIfNeeded();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await shot('completion-task-editor-narrow',false);
  await nav('view-calendar');await nav('view-tasks');
  assert.equal(await draft.getByLabel('Title',{exact:true}).inputValue(),'Unsaved local draft');
  check('Bounded export, explicit exact conversation deletion and reload preserve persisted outcomes');
};
