  await text('#workflow-profile',/no durable execution history/);
  await page.waitForTimeout(2300);
  assert.deepEqual(await control('workflow:read'),before);
  assert.equal(requests.filter(r=>['send_text','decide_pending_request','review_task','workflow_request_target'].includes(r.method)).length,0);
  assert.equal(await pane.locator('a,img,script').count(),0);
  assert.equal(await page.evaluate(()=>window.workflowRan),undefined);
  assert.ok(!(await pane.innerText()).includes('private-fixture.invalid'));
  assert.ok(!(await pane.innerText()).includes('PRIVATE_SECRET'));
  await shot('44-workflows-desktop');
  check('Disconnected cached configuration and partial inventory render without network, callback, decision or store writes');

  await search.fill('daily_briefing');
  assert.equal(await pane.locator('[data-workflow-id]').count(),2);
  await filter.selectOption('decision');
  await row('n8n-pending:'+before.first).focus();
  await page.keyboard.press('Home');
  assert.equal(await row('n8n-pending:'+before.first).getAttribute('aria-pressed'),'true');
  assert.notEqual(await row('n8n-pending:'+before.first).evaluate(el=>getComputedStyle(el).outlineStyle),'none');
  await text('#workflow-profile',/Callback receipt/);
  await pane.getByRole('button',{name:'Open exact decision in Tasks'}).click();
  await page.locator('#view-tasks.active').waitFor();
  await page.locator(`#planner-task-list [data-planner-key="integration:${before.first}"][aria-pressed=true]`).waitFor();
  await text('#planner-task-summary',new RegExp(before.first));
  assert.equal(await draft.inputValue(),'Draft while reviewing automation');
  assert.equal((await control('workflow:read')).pending_unchanged,true);
  await nav('workflows');
  await search.clear();
  await row('n8n-pending:'+before.second).click();
  const late=hold('workflow_request_target');
  await pane.getByRole('button',{name:'Open exact decision in Tasks'}).click();
  assert.equal((await late.received).correlation_id,before.second);
  await row('n8n-pending:'+before.first).click();
  late.release();
  await pane.locator('[aria-pressed=true]').waitFor();
  assert.equal(await pane.getAttribute('class'),'pane workflow-pane active');
  await row('n8n-pending:'+before.second).click();
  const removed=hold('workflow_request_target');
  await pane.getByRole('button',{name:'Open exact decision in Tasks'}).click();
  assert.equal((await removed.received).correlation_id,before.second);
  await control('workflow:request-remove',{id:before.second});
  removed.release();
  await page.locator('#view-tasks.active').waitFor();
  await text('#planner-task-summary',/Decision unavailable/);
  assert.equal(await page.locator('#planner-task-list [aria-pressed=true]').count(),0);
  assert.equal(await page.locator('#planner-decision').isVisible(),false);
  await page.locator('#planner-domain').selectOption('personal');
  await text('#planner-task-summary',/Select a record/);
  assert.equal(await page.locator('#planner-decision').isVisible(),false);
  await nav('workflows');
  assert.equal((await control('workflow:read')).calls.length,0);
  check('Duplicate names retain typed source IDs and exact Tasks navigation rejects removed and superseded targets');

  await search.clear();
  await filter.selectOption('definition');
  await row('n8n-config:daily_briefing').click();
  await control('workflow:receipt',{application_ok:false,http_status:200});
  await text('#workflow-profile',/HTTP 200/);
  await text('#workflow-profile',/Application reported failure/);
  await text('#workflow-profile',/Unverified/);
  assert.ok(!(await pane.innerText()).includes('DO_NOT_DISCLOSE'));
  await control('workflow:receipt',{application_ok:true,http_status:202});
  await text('#workflow-profile',/HTTP 202/);
  await text('#workflow-profile',/Application reported success/);
  await text('#workflow-profile',/Confirmed workflow completion/);
  await row('n8n-config:evening_notes').click();
  await text('#workflow-profile',/HTTP receipt/);
  assert.ok(!(await page.locator('#workflow-profile').innerText()).includes('HTTP 202'));
  await row('n8n-config:daily_briefing').click();
  await shot('45-workflows-outcome');
  check('HTTP receipt and reported application outcomes belong to the exact workflow; completion and other execution history remain unverified');

  const delayed=hold('get_workflow_view');
