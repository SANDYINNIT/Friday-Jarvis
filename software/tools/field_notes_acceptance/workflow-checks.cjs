  await control('workflow:rename',{text:'Most recent local configuration'});
  await pane.getByRole('button',{name:'Refresh local records'}).click();
  await text('#workflow-status',/Reading local records/);
  delayed.release();
  await text('#workflow-profile',/Most recent local configuration/);
  await control('workflow:reader-error',{value:true});
  await pane.getByRole('button',{name:'Refresh local records'}).click();
  await text('#workflow-status',/showing the last snapshot/);
  await text('#workflow-profile',/Most recent local configuration/);
  await control('workflow:reader-error',{value:false});
  await pane.getByRole('button',{name:'Refresh local records'}).click();
  await wait(()=>document.querySelector('#workflow-status').textContent==='');
  await control('workflow:enabled',{value:false});
  await text('#workflow-connection',/disabled or unconfigured locally/);
  await text('#workflow-profile',/Disabled in local configuration/);
  await control('workflow:unloaded');
  await text('#workflow-coverage',/Workflow configuration is unavailable/);
  await control('workflow:restore');
  await text('#workflow-profile',/Most recent local configuration/);
  check('Explicit refresh supersedes delayed reads and shows reader failure, recovery, disabled integration and missing local adapter honestly');

  await nav('command');
  assert.equal(await draft.inputValue(),'Draft while reviewing automation');
  await draft.fill('Intentional new request');
  await draft.press('Enter');
  await wait(()=>document.querySelector('#chat-input').value==='');
  await draft.fill('Draft for later');
  await nav('workflows');
  await control('chunk',{text:'Home kept streaming during workflow review.'});
  await nav('command');
  await text('#cc-chat',/Home kept streaming during workflow review/);
  assert.equal(await draft.inputValue(),'Draft for later');
  await control('finish');
  await nav('workflows');
  await page.setViewportSize({width:760,height:890});
  await shot('46-workflows-compact');
  await pane.getByRole('button',{name:'Go to selected details'}).click();
