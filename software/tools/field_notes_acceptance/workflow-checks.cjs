  const pane=page.locator('#view-workflows');
  const draft=page.getByRole('textbox',{name:'Message FRIDAY'});
  const search=page.locator('#workflow-search'), filter=page.locator('#workflow-filter');
  const row=id=>pane.locator(`[data-workflow-id="${id}"]`);
  const nav=async name=>{
    const menu=page.locator('#nav-toggle');
    if (await menu.isVisible() && !(await page.locator('#app-nav').isVisible())) await menu.click();
    const target=page.locator(`[data-target=view-${name}]`);
    if (!(await target.isVisible())) await page.locator('#nav-more summary').click();
    await target.click();
  };
  const before=await control('workflow:read');
  await draft.fill('Draft while reviewing automation');
  await nav('workflows');
  await text('#workflow-connection',/disconnected at its last check.*stale/);
  await text('#workflow-coverage',/partially readable/);
  await row('n8n-config:daily_briefing').click();
