const assert = require('node:assert/strict');
const path = require('node:path');

module.exports = async ({page,rpc,control,text,wait,shot,check,requests}) => {
  const tasks = page.locator('#view-tasks');
  const calendar = page.locator('#view-calendar');
  const answer = tasks.getByRole('textbox',{name:'Your decision'});
  const action = tasks.getByRole('button',{name:'Record decision'});
  const date = calendar.getByLabel('Agenda date');
  const fixture = await control('planner:snapshot');
  const nav = async target => {
    const item = page.locator(`[data-target=${target}]`);
    if (!await item.isVisible()) await page.locator('#nav-toggle').click();
    await item.click();
  };
  const taskRow = key => tasks.locator(`[data-planner-key="${key}"]`);
  const goDay = async value => { await date.fill(value); await date.dispatchEvent('change'); };

  await page.getByRole('textbox',{name:'Message FRIDAY'}).fill('Preserve this composer draft');
  await nav('view-tasks');
  await text('#planner-task-list',/Review the workshop plan/);
  await taskRow('personal:1').click();
  await text('#planner-task-summary',/Saved personal note/);
  assert.equal(await action.isVisible(),false);
  await taskRow('reminder:1').click();
  await text('#planner-task-summary',/FRIDAY reminder/);
  assert.equal(await action.isVisible(),false);
  await tasks.getByRole('searchbox',{name:'Search tasks'}).fill('Review the workshop plan');
  assert.equal(await tasks.locator('#planner-task-list button').count(),2);
  await tasks.getByLabel('Type').selectOption('reminder');
  assert.equal(await tasks.locator('#planner-task-list button').count(),1);
  assert.equal(await taskRow('reminder:1').getAttribute('aria-pressed'),'true');
  await tasks.getByRole('searchbox',{name:'Search tasks'}).fill('');
  await tasks.getByLabel('Type').selectOption('integration');
  await taskRow(`integration:${fixture.first}`).press('Home');
  const focused = page.locator('#planner-task-list [aria-pressed=true]');
  assert.equal(await focused.evaluate(el=>el===document.activeElement),true);
  assert.notEqual(await focused.evaluate(el=>getComputedStyle(el).outlineStyle),'none');
  assert.equal(await page.getByRole('textbox',{name:'Message FRIDAY'}).inputValue(),'Preserve this composer draft');
  check('Typed records with colliding numeric IDs stay separate through search, filter, selection and keyboard focus');

  await taskRow(`integration:${fixture.second}`).click();
  await text('#planner-task-summary',fixture.second);
  await answer.fill('Use the short outline.');
  await shot('22-tasks-desktop');
  await control('planner:decision-write-failure',{value:true});
  await action.click();
  await text('#planner-decision-status',/couldn't save.*No callback/);
  assert.equal(await answer.inputValue(),'Use the short outline.');
  assert.deepEqual((await control('planner:snapshot')).callbacks,[]);
  await control('planner:decision-write-failure',{value:false});
  await action.click();
  await text('#planner-decision-status',/Decision recorded.*HTTP 200.*application failure.*completion is unverified/);
  await text('#planner-task-summary',/Decision saved/);
  assert.equal(await action.isVisible(),false);
  assert.deepEqual((await control('planner:snapshot')).callbacks,[{id:fixture.second,status:'answered',answer:'Use the short outline.'}]);
  for (const id of [fixture.second,'personal:1',fixture.other,'pr-00000000']) {
    assert.equal((await rpc('decide_pending_request',[id,'repeat'])).ok,false);
  }
  assert.equal((await rpc('get_tasks')).pending.find(row=>row.correlation_id===fixture.first).state,'open');
  await control('planner:reopen');
  await page.reload();
  await nav('view-tasks');
  await taskRow(`integration:${fixture.second}`).click();
  await text('#planner-task-summary',/Decision saved/);
  await text('#planner-task-summary',/Callback receipt and application outcome are unavailable after reload/);
  assert.equal((await control('planner:snapshot')).callbacks.length,1);
  await taskRow(`integration:${fixture.first}`).click();
  await control('planner:decision-disconnected');
  await text('#planner-task-summary',`n8n decision ${fixture.first}:`);
  assert.equal(await action.isVisible(),false);
  check('Exact n8n decision survives reopen, preserves failed input, and separates persistence, callback and application outcome');

  const queued = await rpc('assign_task',['research','Inspect the build notes',null,true]);
  assert.ok(queued.ok);
  await tasks.getByLabel('Type').selectOption('workspace');
  const workspace = taskRow(`workspace:${queued.task.id}`);
  await workspace.filter({hasText:'Running'}).waitFor();
  await control('workspace:release',{goal:'Inspect the build notes'});
  await workspace.filter({hasText:'Awaiting artifact review'}).click();
  await tasks.getByRole('button',{name:/Open exact attempt/}).click();
  await text('#ws-history',/Linked from Tasks/);
  await text('#ws-summary',/Inspect the build notes/);
  await page.locator('#ws-summary').getByRole('button',{name:'Approve result'}).click();
  await text('#ws-summary',/You approved this result/);
  const reviews = requests.filter(item=>item.method==='review_task').map(item=>item.args);
  assert.deepEqual(reviews,[[queued.task.id,'approve',queued.task.attempt]]);
  assert.equal((await control('planner:snapshot')).callbacks.length,1);
  check('Workspace deep link preserves exact task and attempt, and artifact review sends no n8n callback');

  await nav('view-calendar');
  await text('#agenda-status',/Events recorded/);
  await text('#agenda-timezone',/Europe\/Madrid/);
  await goDay('2026-10-25');
  await text('#agenda-list',/Second 02:30/);
  const rendered = await calendar.locator('#agenda-list button strong').allTextContents();
  assert.deepEqual(rendered,['Studio maintenance','Local midnight handoff','First 02:30','Second 02:30']);
  await calendar.locator('#agenda-list button').filter({hasText:'First 02:30'}).click();
  await text('#agenda-detail',/02:30 CEST/);
  await text('#agenda-detail',/03:00 CET/);
  await shot('24-calendar-desktop');
  await calendar.locator('#agenda-list button').filter({hasText:'Second 02:30'}).click();
  await text('#agenda-detail',/02:30 CET/);
  await calendar.locator('#agenda-list button').filter({hasText:'Studio maintenance'}).click();
  await text('#agenda-detail',/All day/);
  await calendar.getByRole('button',{name:'Previous date'}).click();
  assert.equal(await date.inputValue(),'2026-10-24');
  await text('#agenda-list',/No scheduled events/);
  await calendar.getByRole('button',{name:'Next date'}).click();
  assert.equal(await date.inputValue(),'2026-10-25');
  await calendar.getByRole('button',{name:'All dates'}).click();
  assert.equal(await calendar.locator('#agenda-list button').count(),4);
  await calendar.getByRole('button',{name:'Today'}).click();
  assert.equal(await date.inputValue(),fixture.schedule.today);
  await calendar.getByText('Events without a confirmed date or timezone').click();
  await calendar.getByRole('button',{name:/Legacy time/}).click();
  await text('#agenda-detail',/saved time has no timezone/);
  assert.equal(await calendar.getByText('Unconfirmed proposal').count(),0);
  check('Agenda uses Madrid civil dates, DST-aware ordering, distinct all-day dates, date navigation and unplaced legacy times');

  await goDay('2026-10-25');
  await control('planner:calendar-error');
  await text('#agenda-status',/could not be read.*last loaded/);
  assert.equal(await calendar.locator('#agenda-list button').count(),4);
  await control('planner:calendar-empty');
  await text('#agenda-status',/Events recorded/);
  await text('#agenda-list',/No scheduled events/);
  await control('planner:calendar-disconnected');
  await page.reload();
  await nav('view-calendar');
  await text('#agenda-status',/Local schedule is disconnected/);
  assert.ok(await date.isDisabled());
  await control('planner:calendar-connected');
  await text('#agenda-status',/Events recorded/);
  await goDay('2026-10-25');
  await text('#agenda-list',/Studio maintenance/);
  assert.equal(await calendar.locator('#agenda-list button').count(),4);
  await calendar.getByRole('button',{name:'Open chat to schedule'}).click();
  await wait(()=>document.activeElement.id==='chat-input');
  assert.equal(requests.filter(item=>item.method==='send_text').length,0);
  check('Calendar displays reader failure, stale data, empty and disconnected states and restores the saved event set after reload');

  await page.setViewportSize({width:760,height:700});
  await nav('view-calendar');
  await calendar.getByRole('button',{name:/Local midnight handoff/}).click();
  await shot('25-calendar-compact');
  await calendar.getByRole('button',{name:/View selected event/}).click();
  assert.equal(await page.evaluate(()=>document.activeElement.id),'agenda-detail');
  await page.screenshot({path:path.join(__dirname,'screenshots/26-calendar-compact-detail.png')});
  await nav('view-tasks');
  await tasks.getByLabel('Type').selectOption('integration');
  await taskRow(`integration:${fixture.second}`).click();
  await shot('23-tasks-compact');
  await tasks.getByRole('button',{name:/View selected task/}).click();
  assert.equal(await page.evaluate(()=>document.activeElement.id),'planner-task-detail');
  await page.screenshot({path:path.join(__dirname,'screenshots/23b-tasks-compact-detail.png')});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await nav('view-calendar');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  check('Both shipped pages fit compact and narrow widths with keyboard-accessible detail jumps');
};
