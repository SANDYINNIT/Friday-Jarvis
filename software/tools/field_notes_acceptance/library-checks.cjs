const assert = require('node:assert/strict');

module.exports = async ({page,rpc,control,text,wait,shot,check,requests}) => {
  async function open(name) {
    const nav = page.locator(`[data-target="view-${name}"]`);
    const toggle = page.locator('#nav-toggle');
    if (await toggle.isVisible() && !(await page.locator('#app-nav').isVisible())) await toggle.click();
    if (!(await nav.isVisible())) await page.locator('#nav-more summary').click();
    await nav.click();
  }
  const row = (pageName,key) => page.locator(`#${pageName}-library-list [data-library-key="${key}"]`);
  const memory = page.locator('#memory-library-record');
  const content = page.locator('#memory-library-content');
  const filter = page.locator('#memory-library-filter');
  const draft = page.getByRole('textbox',{name:'Message FRIDAY'});
  const initial = await control('library:state');
  const mutations = () => requests.filter(item=>/^(add_memory|update_memory|delete_memory|character_(pin|forget|correct))$/.test(item.method));
  await draft.fill('Live draft stays here');
  await open('memory');
  await row('memory','mem-2').click();
  await text('#memory-library-record', /Opens at ten/);
  await shot('27-memory-desktop');
  await page.locator('#memory-library-search').fill('Journal');
  assert.equal(await row('memory','mem-2').count(),0);
  await row('memory','evt-1').click();
  await text('#memory-library-record',/read-only/);
  assert.equal(await memory.locator('[data-memory-action]').count(),0);
  await page.locator('#memory-library-search').clear();
  await filter.selectOption('legacy');
  await row('memory','exp-2').click();
  await text('#memory-library-record',/Unresolved owner/);
  assert.equal(await memory.locator('[data-memory-action]').count(),0);
  await filter.selectOption('history');
  await row('memory','mem-1').click();
  await text('#memory-library-record',/Superseded/);
  assert.equal(await memory.locator('[data-memory-action]').count(),0);
  assert.equal(mutations().length,0);
  check('Memory search and filters keep colliding facts, experiences, events and unresolved history separate');

  await filter.selectOption('experience');
  await row('memory','exp-1').click();
  await memory.getByRole('button',{name:'Correct',exact:true}).click();
  await content.fill('My unsaved correction');
  await page.locator('#memory-library-reason').fill('Better context');
  assert.equal((await control('library:change')).ok,true);
  await text('#memory-library-record',/Changed elsewhere/);
  assert.equal(await content.inputValue(),'My unsaved correction');
  await page.getByRole('button',{name:'Save memory',exact:true}).click();
  await text('#memory-library-outcome',/changed while you were editing/);
  assert.equal(await content.inputValue(),'My unsaved correction');
  await control('library:fail-reader',{value:true});
  await text('#memory-library-source',/Reader failed/);
  assert.equal(await content.inputValue(),'My unsaved correction');
  await open('knowledge');
  await row('knowledge','notes').click();
  await text('#knowledge-library-record',/Source material/);
  await shot('28-knowledge-desktop');
  await open('memory');
  assert.equal(await content.inputValue(),'My unsaved correction');
  await page.getByRole('button',{name:'Close editor'}).click();
  await control('library:fail-reader',{value:false});
  await memory.getByRole('button',{name:'Pin',exact:true}).click();
  await text('#memory-library-record',/Pinned/);
  assert.deepEqual(mutations().findLast(item=>item.method==='character_pin').args,[initial.owner,'exp-1',true]);
  await memory.getByRole('button',{name:'Forget',exact:true}).click();
  await text('#memory-library-consequence',/leave active retrieval/);
  assert.equal(mutations().filter(item=>item.method==='character_forget').length,0);
  await page.getByRole('button',{name:'Confirm forget'}).click();
  await text('#memory-library-record',/Forgotten/);
  assert.deepEqual(mutations().findLast(item=>item.method==='character_forget').args,[initial.owner,'exp-1']);
  check('Owned experience pin and confirmed forget persist; stale correction and polling preserve the draft');

  await filter.selectOption('fact');
  await row('memory','mem-2').click();
  await memory.getByRole('button',{name:'Correct',exact:true}).click();
  await content.fill('Opens at eleven');
  await page.getByRole('button',{name:'Save memory',exact:true}).click();
  await text('#memory-library-record',/Opens at eleven/);
  const version = (await rpc('get_memory_library')).canonical.current.rows.find(item=>item.key==='Studio hours');
  assert.equal(version.previous_id,2);
  assert.equal(mutations().findLast(item=>item.method==='update_memory').args[0],'mem-2');
  assert.equal(await row('memory','mem-2').count(),0);
  await page.getByRole('button',{name:'Add shared fact'}).click();
  await page.locator('#memory-library-key').fill('Call times');
  await content.fill('Tuesday afternoons');
  await page.getByRole('button',{name:'Save memory',exact:true}).click();
  await text('#memory-library-record',/Tuesday afternoons/);
  check('Canonical correction and add target canonical storage, with retired rows excluded from the current filter');

  await open('knowledge');
  await page.locator('#knowledge-library-filter').selectOption('summary');
  await page.getByRole('button',{name:/Studio hours.*Stale summary.*Shared memory/i}).first().click();
  await text('#knowledge-library-record',/Historical summary/);
  await control('library:break-notes');
  await text('#knowledge-library-source',/Project notes could not be read/);
  check('Knowledge distinguishes source material, saved facts, stale generated summaries and reader failure');

  await open('conversations');
  await row('conversations','Studio_visit.json').click();
  await text('#conversations-library-record',/At ten/);
  await shot('29-conversations-desktop');
  assert.equal(await page.locator('#conversations-library-record img').count(),0);
  assert.equal(await page.evaluate(()=>window.archiveRan),undefined);
  assert.equal(await row('conversations','Active.json').count(),0);
  await row('conversations','Broken.json').click();
  await text('#conversations-library-record',/Could not read this transcript/);
  await row('conversations','Long_session.json').click();
  await text('#conversations-library-record',/preview is incomplete/);
  await page.locator('#conversations-library-search').fill('Studio');
  assert.equal(await row('conversations','Long_session.json').count(),0);
  await row('conversations','Studio_visit.json').focus();
  await page.keyboard.press('Home');
  assert.equal(await row('conversations','Studio_visit.json').getAttribute('aria-pressed'),'true');
  await text('#conversations-library-record',/What time does the studio open/);
  await page.getByRole('button',{name:'Back to Home'}).click();
  assert.equal(await draft.inputValue(),'Live draft stays here');
  assert.deepEqual(await control('library:state'),initial);
  assert.equal(requests.filter(item=>['send_text','stop_turn'].includes(item.method)).length,0);
  check('Read-only transcripts keep literal markup inert, surface malformed and incomplete records, and leave active ownership and composer untouched');

  await draft.fill('An intentional new request');
  await draft.press('Enter');
  await wait(() => document.querySelector('#chat-input').value === '');
  await draft.fill('Draft for a later turn');
  await open('conversations');
  await row('conversations','Studio_visit.json').click();
  await control('chunk',{text:'This response continued while the archive was open.'});
  await page.getByRole('button',{name:'Back to Home'}).click();
  await text('#cc-chat', /This response continued while the archive was open/);
  assert.equal(await draft.inputValue(),'Draft for a later turn');
  assert.equal(requests.filter(item=>item.method==='send_text').length,1);
  await control('finish');
  check('An admitted response continues streaming in Home while browsing the archive');

  await page.reload();
  await page.setViewportSize({width:760,height:890});
  await open('memory');
  await row('memory',version.ref).click();
  await text('#memory-library-record',/Opens at eleven/);
  await shot('30-memory-compact');
  await page.locator('#memory-library-jump').click();
  await shot('30b-memory-compact-detail',false);
  await open('knowledge');
  await row('knowledge',`fact:${version.id}`).click();
  await text('#knowledge-library-record',/Independent validation is not recorded/);
  await shot('31-knowledge-compact');
  await page.locator('#knowledge-library-jump').click();
  await shot('31b-knowledge-compact-detail',false);
  await open('conversations');
  await row('conversations','Studio_visit.json').click();
  await text('#conversations-library-record',/What time does the studio open/);
  await shot('32-conversations-compact');
  await page.locator('#conversations-library-jump').click();
  await shot('32b-conversations-compact-detail',false);
  await page.setViewportSize({width:390,height:800});
  await page.getByRole('button',{name:'Go to selected details'}).click();
  assert.equal(await page.evaluate(()=>document.activeElement.id),'conversations-library-detail');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
  await control('library:empty-archive');
  await text('#conversations-library-list',/No records yet/);
  await control('library:broken-archive');
  await text('#conversations-library-source',/Could not read the saved archive/);
  check('Reload reads persisted edits and transcripts; compact and narrow controls work; archive empty and failure are distinct');
};
