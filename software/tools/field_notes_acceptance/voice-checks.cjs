const assert = require('node:assert/strict');

module.exports = async ({page,rpc,control,text,wait,shot,check,requests,hold}) => {
  const nav = name => page.locator(`[data-target=view-${name}]`);
  const voice = page.locator('#view-voice');
  const pause = page.locator('#vs-pause');
  const input = page.getByRole('textbox',{name:'Message FRIDAY'});
  await input.fill('My shared draft');
  await nav('voice').click();
  assert.equal(await page.evaluate(()=>document.activeElement.id),'main');
  await text('#vs-connection',/HUD bridge connected/);
  await text('#vs-capture',/Running.*recent frame/);
  await text('#vs-capture-setting',/Continuous capture configured/);
  await text('#vs-preference',/Allowed for this session/);
  await text('#vs-followup',/^Open$/);
  await wait(() => document.querySelector('#vs-wake').textContent !== 'No match reported this session');
  const count = requests.filter(item=>item.method==='get_voice_screen').length;
  await page.waitForTimeout(2400);
  assert.ok(requests.filter(item=>item.method==='get_voice_screen').length > count);
  const idle = await control('voice:read');
  assert.deepEqual(idle.calls,[]);
  assert.deepEqual(idle.queued,[]);
  assert.equal(requests.filter(item=>['set_paused','stop_turn','send_text'].includes(item.method)).length,0);
  assert.equal(await input.inputValue(),'My shared draft');
  await shot('33-voice-desktop');
  check('Opening and polling the shipped page read status without media operations or preference writes');

  await control('voice:status',{state:'listening',detail:'Listening for a command'});
  await text('#vs-input',/Receiving voice input/);
  await control('voice:status',{state:'thinking',detail:'Transcribing and routing'});
  await text('#vs-input',/Transcribing voice input/);
  await control('voice:status',{state:'thinking',detail:'FRIDAY is working'});
  await text('#vs-input',/Processing a request/);
  await control('voice:vision',{value:true});
  await control('voice:health',{value:{running:true,last_frame_age:100}});
  await text('#vs-request',/Screen request in progress/);
  await text('#vs-capture',/last frame is stale/);
  await voice.getByText('Diagnostics',{exact:true}).click();
  await text('#vs-synthesis-result',/Local neural voice produced audio/);
  await text('#vs-frame-age',/100.0 s/);
  await control('voice:health-error',{value:true});
  await text('#vs-capture',/Capture status could not be read/);
  await control('voice:status',{state:'error',detail:'<img src=x onerror=window.bad=true> PRIVATE_RUNTIME_DETAIL'});
  await text('#vs-input',/Runtime reported an error/);
  assert.ok(!(await voice.innerText()).includes('PRIVATE_RUNTIME_DETAIL'));
  assert.equal(await voice.locator('img,script').count(),0);
  assert.equal(await page.evaluate(()=>window.bad),undefined);
  check('Listening, transcription, processing, screen freshness and vision activity are distinct, with sanitized diagnostics');

  await control('voice:frame',{name:'old'});
  await text('#vs-playback',/playback unconfirmed/);
  const oldId = (await control('voice:read')).utterances.old;
  await control('voice:ack',{name:'old',event:'first_audio'});
  const lateSpeech = hold('get_voice_screen');
  const staleSpeech = await lateSpeech.received;
  assert.ok(['recent','unobserved'].includes(staleSpeech.speaking.playback));
  await control('voice:stop-audio');
  await page.evaluate(utterance=>window.FRIDAY_EVENT({type:'stop',data:{utterance}}),oldId);
  await text('#vs-playback',/^Unavailable$/);
  lateSpeech.release();
  await control('voice:ack',{name:'old',event:'first_audio'});
  await text('#vs-playback',/Speech cancelled.*device stop unconfirmed/);
  await control('voice:frame',{name:'new'});
  await control('voice:ack',{name:'old',event:'progress'});
  await text('#vs-playback',/playback unconfirmed/);
  await control('voice:ack',{name:'new',event:'first_audio'});
  await text('#vs-playback',/recently acknowledged/);
  const progress = (await rpc('get_speech')).last_progress_at;
  await control('voice:ack',{name:'old',event:'drained'});
  const speech = await rpc('get_speech');
  assert.equal(speech.last_progress_at,progress);
  assert.equal(speech.drained,false);
  await control('voice:ack',{name:'new',event:'drained'});
  await text('#vs-playback',/reported playback drained/);
  check('Only the current speech frame can acknowledge playback or mark it drained');

  const stale = hold('get_voice_screen');
  assert.equal((await stale.received).listening.paused,false);
  const delayed = hold('set_paused');
  await pause.focus();
  await page.keyboard.press('Enter');
  assert.equal((await delayed.received).accepted,true);
  await text('#vs-action-result',/Waiting for the server/);
  await text('#vs-preference',/Allowed for this session/);
  await page.keyboard.press('Enter');
  assert.equal(requests.filter(item=>item.method==='set_paused').length,1);
  delayed.release();
  await text('#vs-action-result',/paused for this session/);
  stale.release();
  await text('#vs-preference',/Paused for this session/);
  assert.equal(await pause.innerText(),'Resume voice input');
  await control('voice:queue-error',{value:true});
  await pause.click();
  await text('#vs-action-result',/previous setting was kept/);
  assert.equal((await control('voice:read')).paused,true);
  await text('#vs-preference',/Paused for this session/);
  await control('voice:queue-error',{value:false});
  await pause.click();
  await text('#vs-action-result',/allowed for this session/);
  const voiceState = await control('voice:read');
  assert.deepEqual(voiceState.queued.map(frame=>frame.voice_paused),[true,false]);
  assert.deepEqual(voiceState.calls,['resume']);
  check('Session changes require acknowledgement; stale polls, duplicate activation and a failed queue write preserve the confirmed setting');

  await control('voice:reader-error',{value:true});
  await text('#vs-connection',/status unavailable/);
  assert.equal(await pause.isVisible(),false);
  await control('voice:reader-error',{value:false});
  await text('#vs-connection',/HUD bridge connected/);
  await control('status_error',{value:true});
  await text('#vs-connection',/HUD bridge unavailable/);
  await control('status_error',{value:false});
  await text('#vs-connection',/HUD bridge connected/);
  await nav('command').click();
  assert.equal(await input.inputValue(),'My shared draft');
  await input.press('Enter');
  await wait(()=>document.querySelector('#chat-input').value==='');
  await input.fill('Draft for later');
  await nav('voice').click();
  await control('chunk',{text:'Response kept streaming on Voice & Screen.'});
  await nav('command').click();
  await text('#cc-chat',/Response kept streaming/);
  assert.equal(await input.inputValue(),'Draft for later');
  await nav('voice').click();
  await voice.getByRole('button',{name:'Stop this turn'}).click();
  await text('#vs-preference',/Allowed for this session/);
  assert.equal((await control('voice:read')).paused,false);
  assert.equal(requests.filter(item=>item.method==='stop_turn').length,1);
  check('Reader failures and reconnect recover without hiding the Home draft, streaming response or scoped Stop');

  await control('voice:health-error',{value:false});
  await control('voice:health',{value:{running:true,last_frame_age:0.4}});
  await control('voice:vision',{value:false});
  await text('#vs-capture',/Running.*recent frame/);
  await wait(()=>!document.querySelector('#toast').classList.contains('show'));
  if (await voice.locator('details').getAttribute('open') !== null) await voice.locator('summary').click();
  await page.setViewportSize({width:760,height:890});
  await shot('34-voice-compact');
  await page.setViewportSize({width:390,height:820});
  await shot('35-voice-narrow');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
  await pause.focus();
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(()=>document.activeElement.tagName),'SUMMARY');
  await page.keyboard.press('Enter');
  assert.notEqual(await voice.locator('summary').evaluate(el=>getComputedStyle(el).outlineStyle),'none');
  await text('#vs-frame-age',/0.4 s/);
  await wait(()=>{
    const summary = document.querySelector('#view-voice summary');
    const main = document.querySelector('#main').getBoundingClientRect();
    const rect = summary.getBoundingClientRect();
    return rect.top >= main.top && rect.bottom <= main.bottom &&
      rect.bottom < document.querySelector('#chat-form').getBoundingClientRect().top;
  });
  assert.equal(await input.inputValue(),'Draft for later');
  await shot('35b-voice-narrow-diagnostics',false);
  check('Desktop, compact and narrow layouts preserve labels, keyboard focus, scrolling and composer clearance');
};
