const assert=require('node:assert/strict');
module.exports=async({page,rpc,control,text,wait,shot,check,requests,hold})=>{
  const draft=page.getByRole('textbox',{name:'Message FRIDAY'});
  await draft.fill('Keep this chat draft while configuring n8n');
  const nav=page.locator('[data-target=view-settings]');
  if(!(await nav.isVisible()))await page.locator('#nav-more summary').click();
  await nav.click();
  const refresh=()=>page.locator('#settings-refresh').click();
  await text('#n8n-state',/Disabled/);
  assert.equal((await control('n8n:read')).connections,0);
  assert.equal((await control('n8n:read')).saved,false);
  await refresh();await page.waitForTimeout(800);
  assert.equal((await control('n8n:read')).connections,0);
  check('Opening/polling/refresh writes no config and makes zero n8n requests');
  await page.locator('#n8n-deployment').fill('https://automation.invalid');
  await page.locator('#n8n-secret').fill('synthetic_'+'0'.repeat(40));
  await page.locator('#n8n-cap-chat').check();
  await control('n8n:fail-write',{value:true});
  await page.locator('#n8n-save').click();
  await text('#n8n-result',/Save not confirmed/);
  assert.equal(await page.locator('#n8n-secret').inputValue(),'synthetic_'+'0'.repeat(40));
  assert.equal((await control('n8n:read')).saved,false);
  await control('n8n:fail-write',{value:false});await page.locator('#n8n-save').click();
  await text('#n8n-result',/Saved. No connection/);
  await wait(()=>document.querySelector('#n8n-secret').value==='');
  assert.equal((await control('n8n:read')).connections,0);
  check('Failed authoritative save preserves draft; successful save clears secrets without connecting');
  const oldSnapshot=hold('get_n8n');
  await refresh();await oldSnapshot.received;
  await page.locator('#n8n-test').click();
  await text('#n8n-result',/ready/);
  oldSnapshot.release();
  await page.getByText('Connection and receipt details',{exact:true}).click();
  await text('#n8n-observation',/Observation: observed/);
  await page.getByText('Connection and receipt details',{exact:true}).click();
  check('A delayed pre-test snapshot cannot replace the newer connection observation');

  await text('#n8n-result',/ready/);
  assert.deepEqual((await control('n8n:read')).operations,['status']);
  assert.equal(await page.locator('#n8n-enabled').isChecked(),false);
  check('Explicit connection test is separate from enablement and sends status only');
  await page.locator('#n8n-enabled').check();
  await control('n8n:external');await refresh();
  await text('#n8n-result',/changed elsewhere/);
  assert.equal(await page.locator('#n8n-save').isDisabled(),true);
  await page.locator('#n8n-cancel').click();
  await page.locator('#n8n-enabled').check();
  const delayed=hold('set_n8n');await page.locator('#n8n-save').click();await delayed.received;
  await page.locator('#n8n-enabled').uncheck();
  delayed.release();await page.waitForTimeout(250);
  assert.equal(await page.locator('#n8n-enabled').isChecked(),false);
  assert.equal(await page.locator('#n8n-save').isDisabled(),false);
  await page.locator('#n8n-save').click();await text('#n8n-result',/Saved/);
  await control('n8n:reopen');await refresh();await text('#n8n-state',/Disabled/);
  assert.equal((await control('n8n:read')).connections,1);
  check('Stale/delayed writes preserve newer edits and reopen retains acknowledged settings');
  await control('n8n:fail-read',{value:true});await refresh();await text('#n8n-state',/unavailable or stale/);
  assert.equal(await page.locator('#n8n-save').isDisabled(),true);
  await control('n8n:fail-read',{value:false});await refresh();await text('#n8n-state',/Disabled/);
  assert.equal(await draft.inputValue(),'Keep this chat draft while configuring n8n');
  assert.equal(await page.locator('#settings-n8n img').count(),0);
  assert.ok(!(await page.locator('#settings-n8n').innerText()).includes('automation.invalid'));
  assert.ok(!(await page.locator('#settings-n8n').innerText()).includes('synthetic_'));
  await control('n8n:proposal');
  await page.locator('[data-target=view-command]').click();
  await text('#home-n8n-review',/waiting for your exact review/);
  await page.locator('#home-n8n-settings').click();
  await text('#n8n-proposal-text',/Synthetic <script>inert/);
  assert.equal(await page.locator('#n8n-proposal script').count(),0);
  await page.locator('#n8n-request-cancel').click();
  await page.locator('#n8n-proposal').waitFor({state:'hidden'});
  assert.equal((await control('n8n:read')).connections,1);
  check('Home points to exact n8n review; cancellation records only that request and sends nothing');
  await page.locator('#settings-n8n').evaluate(el=>el.scrollIntoView({block:'start'}));await shot('n8n-settings-desktop',false);
  await page.setViewportSize({width:620,height:930});
  await page.locator('#settings-n8n').evaluate(el=>el.scrollIntoView({block:'start'}));await shot('n8n-settings-compact',false);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.equal(requests.filter(x=>x.method==='send_text').length,0);
  check('Reader failures are stale, draft survives, private values stay hidden, compact layout fits');
  if(await page.locator('.public-town-exclusion').count()){
    await page.setViewportSize({width:1440,height:930});
    const before=requests.filter(x=>x.method==='get_town_view').length;
    await page.locator('[data-target=view-lab]').click();
    await page.getByRole('heading',{name:'Living Town is not included in this public package'}).waitFor();
    await page.waitForTimeout(300);
    assert.equal(requests.filter(x=>x.method==='get_town_view').length,before);
    check('Public Town exclusion shows a truthful notice without Town reader or asset requests');
  }

};
