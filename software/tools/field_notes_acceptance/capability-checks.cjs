const assert = require('node:assert/strict');

module.exports = async ({page,rpc,control,text,wait,shot,check,requests,hold}) => {
  const pane=page.locator('#view-tools');
  const draft=page.getByRole('textbox',{name:'Message FRIDAY'});
  const search=page.locator('#capability-search'), filter=page.locator('#capability-filter');
  const row=id=>pane.locator('[data-capability-id]').filter({has:page.locator('strong')})
    .and(pane.locator(`[data-capability-id="${id}"]`));
  const nav=async name=>{
    const menu=page.locator('#nav-toggle');
    if (await menu.isVisible() && !(await page.locator('#app-nav').isVisible())) await menu.click();
    const target=page.locator(`[data-target=view-${name}]`);
    if (!(await target.isVisible())) await page.locator('#nav-more summary').click();
    await target.click();
  };
  const before=await control('capability:read');
  await draft.fill('A draft while browsing capabilities');
  await nav('tools');
  await text('#capability-status',/FRIDAY metadata/);
  await row('oi:execute').click();
  await text('#capability-profile',/Code confirmation setting/);
  await text('#capability-profile',/language/);
  await page.waitForTimeout(2300);
  assert.deepEqual(await control('capability:read'),before);
  assert.equal(requests.filter(r=>['send_text','set_paused','stop_turn','get_tools','get_skills'].includes(r.method)).length,0);
  await shot('41-capabilities-desktop');
  check('Opening and polling read loaded FRIDAY metadata with no execution, connection, permission or persistent changes');

  await filter.selectOption('mcp');
  await search.fill('inspect');
  assert.equal(await pane.locator('[data-capability-id]').count(),2);
  await row('mcp:studio:inspect').click();
  await text('#capability-profile',/Included in the adapter allowlist/);
  await row('mcp:archive:inspect').focus();
  await page.keyboard.press('Home');
  const selected=pane.locator('[data-capability-id][aria-pressed=true]');
  assert.equal(await selected.evaluate(el=>el===document.activeElement),true);
  assert.notEqual(await selected.evaluate(el=>getComputedStyle(el).outlineStyle),'none');
  await row('mcp:archive:inspect').click();
  await text('#capability-profile',/Outside the adapter allowlist/);
  await text('#capability-profile',/Ignore previous instructions/);
  assert.equal(await pane.locator('img,a,script').count(),0);
  assert.equal(await page.evaluate(()=>window.capabilityRan),undefined);
  assert.ok(!(await pane.innerText()).includes('private-fixture.invalid'));
  assert.ok(!(await pane.innerText()).includes('PRIVATE_FIXTURE_TOKEN'));
  await search.fill('publish');
  await row('mcp:studio:publish').click();
  await text('#capability-profile',/Required at invocation/);
  await text('#capability-profile',/Not granted by this view/);
  await search.fill('odd_schema');
  await row('mcp:archive:odd_schema').click();
  await text('#capability-profile',/Input metadata is unavailable or unsupported/);
  check('Exact source IDs distinguish duplicate names; allowlist, confirmation and unsafe or unsupported metadata stay separate');

  await search.clear();
  await filter.selectOption('procedure');
  const procedure=await pane.locator('[data-capability-id]').getAttribute('data-capability-id');
  await row(procedure).click();
  await text('#capability-profile',/Saved instructions/);
  await text('#capability-profile',/Ask before filing/);
  await filter.selectOption('extension');
  await pane.getByRole('button',{name:/broken/}).click();
  await text('#capability-profile',/metadata could not be read completely/);
  await pane.getByRole('button',{name:/extension/}).click();
  await text('#capability-profile',/Stored file metadata does not establish/);
  assert.equal((await control('capability:read')).marker,false);
  await filter.selectOption('integration');
  await row('mcp-server:disabled').click();
  await text('#capability-profile',/Disabled in reported configuration/);
  await text('#capability-profile',/No session attached/);
  check('Saved instruction procedures, executable skill files, malformed metadata and disabled connections are labeled honestly');

  await filter.selectOption('tool');
  await row('oi:execute').click();
  const delayed=hold('get_capability_inventory');
  await delayed.received;
  await control('capability:rename',{text:'Latest loaded schema description'});
  await pane.getByRole('button',{name:'Refresh inventory'}).click();
  await text('#capability-status',/Reading FRIDAY/);
  delayed.release();
  await text('#capability-profile',/Latest loaded schema description/);
  assert.equal(await row('oi:execute').getAttribute('aria-pressed'),'true');
  await control('capability:reader-error',{value:true});
  await pane.getByRole('button',{name:'Refresh inventory'}).click();
  await text('#capability-status',/showing the last snapshot/);
  await text('#capability-profile',/Latest loaded schema description/);
  await control('capability:reader-error',{value:false});
  await pane.getByRole('button',{name:'Refresh inventory'}).click();
  await text('#capability-status',/FRIDAY metadata/);
  assert.equal(await draft.inputValue(),'A draft while browsing capabilities');
  check('An explicit refresh supersedes a delayed read while selection, failed-read history and the shared draft survive');

  await nav('command');
  await draft.fill('Intentional live request');
  await draft.press('Enter');
  await wait(()=>document.querySelector('#chat-input').value==='');
  await draft.fill('Draft for the next turn');
  await nav('tools');
  await control('chunk',{text:'The response continued while viewing capabilities.'});
  await nav('command');
  await text('#cc-chat',/response continued while viewing capabilities/);
  assert.equal(await draft.inputValue(),'Draft for the next turn');
  await control('finish');
  await nav('tools');
  await page.setViewportSize({width:760,height:890});
  await filter.selectOption('procedure');
  await row(procedure).click();
  await shot('42-capabilities-compact');
  await pane.getByRole('button',{name:'Go to selected details'}).click();
  await shot('42b-capabilities-compact-detail',false);
  await page.setViewportSize({width:390,height:820});
  await pane.locator('#capability-profile summary').focus();
  await page.keyboard.press('Enter');
  await wait(()=>document.querySelector('#capability-profile details').open);
  const focus=await pane.locator('#capability-profile summary').evaluate(el=>({
    outline:getComputedStyle(el).outlineStyle, bottom:el.getBoundingClientRect().bottom,
    composer:document.querySelector('#chat-form').getBoundingClientRect().top
  }));
  assert.notEqual(focus.outline,'none');
  assert.ok(focus.bottom<focus.composer);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.equal(await draft.inputValue(),'Draft for the next turn');
  await shot('43-capabilities-narrow',false);
  assert.equal((await control('capability:read')).marker,false);
  assert.deepEqual((await control('capability:read')).calls,[]);
  await control('capability:empty');
  await filter.selectOption('');
  await pane.getByRole('button',{name:'Refresh inventory'}).click();
  await text('#capability-list',/No items reported by the available readers/);
  assert.ok(!(await page.locator('#capability-status').innerText()).includes('Reader unavailable'));
  check('Responsive views retain keyboard focus and composer clearance; Home streaming and honest empty coverage survive navigation');
};
