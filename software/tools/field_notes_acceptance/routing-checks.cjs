const assert = require('node:assert/strict');

module.exports = async ({page,rpc,control,text,wait,shot,check,requests}) => {
  const core = page.locator('#view-core');
  const agents = page.locator('#view-agents');
  const draft = page.getByRole('textbox',{name:'Message FRIDAY'});
  const select = page.locator('#routing-filter');
  const search = page.locator('#routing-search');
  const duty = page.locator('#routing-duty article');
  const row = id => agents.locator('[data-route-id]').filter({hasText:id});
  const nav = async name => {
    const menu = page.locator('#nav-toggle');
    if (await menu.isVisible() && !(await page.locator('#app-nav').isVisible())) await menu.click();
    const target = page.locator(`[data-target=view-${name}]`);
    if (!(await target.isVisible())) await page.locator('#nav-more summary').click();
    await target.click();
  };
  const before = await control('routing:read');
  await draft.fill('Routing-page draft');
  await nav('core');
  await text('#routing-core-status',/Read-only routing snapshot/);
  assert.deepEqual(await core.locator('#routing-order strong').allTextContents(),
    (await rpc('get_routing_view')).routes.filter(item=>item.position).map(item=>{
      const names={modal:'Modal',groq:'Groq',gemini:'Gemini',openrouter:'OpenRouter',ollama:'Ollama'};
      return [names[item.provider],item.model].join(' · ');
    }));
  const routeOrders = () => core.locator('#routing-order li').count();
  assert.equal(await routeOrders(),before.order.length);
  const absent = await control('routing:modal',{value:false});
  await core.getByRole('button',{name:'Refresh status'}).click();
  await wait(n=>document.querySelectorAll('#routing-order li').length===n,absent.order.length);
  assert.equal(await core.locator('#routing-order li').first().getByText(/Groq/).count(),1);
  await control('routing:modal',{value:true});
  await wait(n=>document.querySelectorAll('#routing-order li').length===n,before.order.length);
  const untouched = await control('routing:read');
  assert.deepEqual(untouched.stores,before.stores);
  assert.deepEqual(untouched.calls,[]);
  assert.equal(requests.filter(item=>item.method==='get_core' || item.method==='get_ai_agents').length<=1,true);
  assert.equal(await draft.inputValue(),'Routing-page draft');
  check('Resolver-derived order handles optional Modal; opening, polling and refreshing do not write or call providers');

  await control('routing:start');
  await text('#routing-duty',/studio-main/);
  assert.equal((await control('routing:fallback')).late,false);
  await text('#routing-duty',/studio-fallback/);
  assert.match(await duty.nth(1).innerText(),/studio-main/);
  assert.match(await duty.nth(0).innerText(),/Last successful service\s+Not reported/);
  await shot('36-core-desktop');
  check('Brain fallback changes its own duty while vision keeps the exact Modal deployment; stale success is ignored');

  await core.getByRole('button',{name:'Browse routes'}).click();
  await select.selectOption('brain');
  await search.fill(before.order[0]);
  assert.equal(await row('studio-main').count(),1);
  assert.equal(await row('studio-secondary').count(),1);
  await row('studio-secondary').focus();
  await page.keyboard.press('Home');
  const chosen = agents.locator('[data-route-id][aria-pressed=true]');
  assert.equal(await chosen.evaluate(el=>el===document.activeElement),true);
  assert.notEqual(await chosen.evaluate(el=>getComputedStyle(el).outlineStyle),'none');
  await row('studio-secondary').click();
  await text('#routing-profile',/Exact catalog binding/);
  const route = (await rpc('get_routing_view')).routes.find(item=>item.deployment==='studio-secondary');
  await shot('37-agents-desktop');
  await agents.getByRole('button',{name:'Open character in AI Roster'}).click();
  await page.locator('#view-roster.active').waitFor();
  await wait(id=>document.querySelector(`#fn-person-list [data-entry="${id}"][aria-pressed="true"]`)!==null,route.character_id);
  assert.ok(requests.some(item=>item.method==='get_identity_views'&&item.args[0]===route.character_id));
  await nav('agents');
  check('Search, keyboard selection and Roster handoff use the exact deployment and catalog identity');

  await search.clear();
  await row('fixture-disabled').click();
  await agents.locator('#routing-profile dd').getByText('Disabled',{exact:true}).waitFor();
  await row('fixture-retired').click();
  await agents.locator('#routing-profile dd').getByText('Retired',{exact:true}).waitFor();
  await control('routing:cooldown');
  await search.fill(before.order[0]);
  await row('studio-main').click();
  await text('#routing-profile',/Model cooling down/);
  assert.match(await agents.locator('#routing-profile').innerText(),/Provider health\s+Unknown/);
  await select.selectOption('workflow');
  await search.clear();
  await row('workflow-local').click();
  await text('#routing-profile',/Procedural service route/);
  assert.equal(await agents.locator('#routing-character').isVisible(),false);
  await control('routing:unsafe',{value:true});
  const safe = await rpc('get_routing_view');
  assert.ok(!JSON.stringify(safe).includes('routeMarkupRan'));
  assert.ok(!JSON.stringify(safe).includes('fixture-private.invalid'));
  assert.ok(!JSON.stringify(safe).includes('fixture-token'));
  assert.equal(await agents.locator('img,script').count(),0);
  await control('routing:unsafe',{value:false});
  check('Catalog retirement, disablement, cooldown, procedural services and unknown health stay distinct; unsafe metadata is omitted');

  assert.deepEqual(await control('routing:complete'),{brain:true,vision:true});
  await control('routing:unbound');
  await agents.getByRole('button',{name:'Open AI Core'}).click();
  await text('#routing-duty',/unmapped-lab.*Unbound/);
  assert.match(await duty.nth(0).innerText(),/Last successful service\s+.*studio-fallback/);
  await control('routing:restart');
  await wait(()=>document.querySelector('#routing-duty').textContent.includes('No active observation')&&
    !document.querySelector('#routing-duty').textContent.includes('unmapped-lab'));
  await text('#routing-duty',/studio-fallback/);
  await control('routing:reader-error',{value:true});
  await core.getByRole('button',{name:'Refresh status'}).click();
  await text('#routing-core-status',/showing the last snapshot/);
  await text('#routing-duty',/studio-fallback/);
  assert.match(await duty.nth(0).innerText(),/Duty at last read/);
  await control('routing:reader-error',{value:false});
  await core.getByRole('button',{name:'Refresh status'}).click();
  await text('#routing-core-status',/Read-only routing snapshot/);
  await control('routing:gate',{value:false});
  await wait(()=>!document.querySelector('#routing-duty').textContent.includes('studio-fallback'));
  assert.match(await duty.nth(0).innerText(),/Current duty\s+Unavailable/);
  await control('routing:gate',{value:true});
  await text('#routing-duty',/studio-fallback/);
  check('Unbound duty stays explicit, restart clears current duty, and failed reads retain a clearly stale snapshot');

  await nav('command');
  assert.equal(await draft.inputValue(),'Routing-page draft');
  await draft.press('Enter');
  await wait(()=>document.querySelector('#chat-input').value==='');
  await draft.fill('Draft during routing review');
  await nav('core');
  await control('chunk',{text:'Streaming during routing review'});
  await nav('command');
  await text('#cc-chat',/Streaming during routing review/);
  assert.equal(await draft.inputValue(),'Draft during routing review');
  await control('finish');
  await nav('core');
  await page.setViewportSize({width:760,height:890});
  await shot('38-core-compact');
  await core.getByRole('button',{name:'Browse routes'}).click();
  await select.selectOption('brain');
  await search.fill('studio-fallback');
  await row('studio-fallback').first().click();
  await text('#routing-profile',/Fallback candidate/);
  await shot('39-agents-compact');
  await page.setViewportSize({width:390,height:820});
  await agents.getByRole('button',{name:'Go to selected details'}).click();
  assert.equal(await page.evaluate(()=>document.activeElement.id),'routing-detail');
  await agents.locator('summary').focus();
  await page.keyboard.press('Enter');
  await wait(()=>document.querySelector('#routing-profile details').open);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.equal(await draft.inputValue(),'Draft during routing review');
  await shot('40-agents-narrow',false);
  assert.deepEqual((await control('routing:read')).calls,[]);
  check('Home streaming and composer survive navigation; desktop, compact and narrow views retain focus and readable details');
};
