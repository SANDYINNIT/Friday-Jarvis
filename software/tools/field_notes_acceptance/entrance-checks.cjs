const assert=require('node:assert/strict');
const fs=require('node:fs');const path=require('node:path');
module.exports=async({page,input,shot,check,checks,control,requests,errors,external,captures,fakeWindow})=>{
  await page.waitForFunction(()=>window.FieldEntrance);
  await page.waitForFunction(()=>window.FieldEntrance.snapshot().plays===1);
  await page.locator('#friday-entrance').waitFor({state:'hidden'});
  await input.fill('Preserve this draft through the opening animation');
  const open=()=>{fakeWindow.opening_revision++;fakeWindow.opening.revision++;};
  open();
  await page.locator('#friday-entrance').waitFor({state:'visible'});
  // Capture a reproducible mid-reveal frame; screenshot font waits must not
  // race the final fade. This pauses an already native-triggered animation.
  await page.evaluate(()=>document.getAnimations().filter(a=>a.effect?.target?.closest?.('#friday-entrance')).forEach(a=>{a.pause();a.currentTime=500;}));
  assert.equal(await page.locator('#friday-entrance').evaluate(e=>getComputedStyle(e).opacity),'1');
  await shot('opening-desktop',false);
  await page.evaluate(()=>document.getAnimations().forEach(a=>{if(a.playState==='paused')a.play();}));
  assert.equal(await page.locator('#friday-entrance').evaluate(e=>getComputedStyle(e).pointerEvents),'none');
  assert.equal(await input.inputValue(),'Preserve this draft through the opening animation');
  await page.locator('#friday-entrance').waitFor({state:'hidden'});
  check('First native opening and subsequent Open render without direct play(), blocking input or readiness claims');
  const plays=await page.evaluate(()=>window.FieldEntrance.snapshot().plays);
  fakeWindow.opening.visible=false;
  await page.waitForFunction(()=>window.FieldEntrance.snapshot().reason==='Waiting for the window');
  open();
  await page.waitForFunction(()=>window.FieldEntrance.snapshot().pending);
  assert.equal(await page.evaluate(()=>window.FieldEntrance.snapshot().plays),plays);
  fakeWindow.opening.visible=true;
  await page.waitForFunction(p=>window.FieldEntrance.snapshot().plays>p,plays);
  const once=await page.evaluate(()=>window.FieldEntrance.snapshot().plays);
  await page.evaluate(()=>{window.FieldEntrance.observe(0);window.FieldEntrance.observe(0);});
  await page.locator('#friday-entrance').waitFor({state:'hidden'});
  assert.equal(await page.evaluate(()=>window.FieldEntrance.snapshot().plays),once);
  check('A hidden native Open queues until visible and replays once; repeated/stale reads do not');
  open();await page.locator('#friday-entrance').waitFor({state:'visible'});
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#friday-entrance').isVisible(),false);
  await page.emulateMedia({reducedMotion:'reduce'});
  const before=await page.evaluate(()=>window.FieldEntrance.snapshot().plays);
  open();await page.waitForFunction(()=>window.FieldEntrance.snapshot().reason.includes('Reduced motion'));
  assert.equal(await page.evaluate(()=>window.FieldEntrance.snapshot().plays),before);
  assert.equal(await page.locator('#friday-entrance').isVisible(),false);
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.evaluate(()=>localStorage.setItem('friday.ui.reducedMotion','1'));
  open();await page.waitForTimeout(1200);
  assert.equal(await page.locator('#friday-entrance').isVisible(),false);
  await page.evaluate(()=>localStorage.removeItem('friday.ui.reducedMotion'));
  check('Escape/cancellation and OS or saved reduced-motion preference suppress animation safely');
  await page.setViewportSize({width:390,height:844});
  open();await page.locator('#friday-entrance').waitFor({state:'visible'});await page.waitForTimeout(330);
  await shot('opening-narrow',false);
  await page.locator('#friday-entrance').waitFor({state:'hidden'});
  assert.equal(await input.inputValue(),'Preserve this draft through the opening animation');
  const stop=await page.locator('#btn-stop').boundingBox();assert.ok(stop.x+stop.width<=390);
  assert.ok(!requests.some(r=>['send_text','set_startup','window_action'].includes(r.method)));
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  check('Narrow reveal preserves drafts, Stop bounds and passive bridge behavior');
  fs.writeFileSync(path.join(captures,'opening-verification.json'),JSON.stringify({checks,errors,external},null,2));
  console.log('Opening evidence: '+captures);
};
