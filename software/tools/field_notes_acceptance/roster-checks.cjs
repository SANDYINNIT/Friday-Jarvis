/* Actual clicks on shipped Roster, backed by real synthetic identity stores. */
const assert = require('node:assert/strict');
module.exports = async ({page,rpc,control,text,wait,shot,check,requests}) => {
  const directory = page.locator('#fn-person-list');
  const profile = page.locator('#fn-profile');
  const search = page.getByRole('searchbox',{name:'Find a character or service'});
  const refresh = async () => { await page.locator('#fn-roster-refresh').click(); };
  const nav = async target => {
    if (!(await page.locator('[data-target='+target+']').isVisible())) await page.locator('#nav-toggle').click();
    await page.locator('[data-target='+target+']').click();
  };
  const select = async id => { await directory.locator('[data-entry="'+id+'"]').click(); };
  const fixture = await control('roster:read');
  const {primary,fallback,workshop:local} = fixture.ids;
  const names = Object.fromEntries(fixture.pair.roster.characters.map(row=>[row.id,row.name]));
  await nav('view-roster');
  await text('#fn-roster-status',/Catalog revision/);
  assert.equal(await directory.locator('[data-entry]').count(),3);
  assert.ok(!requests.some(item=>item.method==='get_roster'));
  assert.ok(!requests.some(item=>item.method==='get_lab'));
  await select(primary);
  await text('#fn-profile',names[primary]);
  assert.match(await profile.innerText(),/fixture-primary/);
  assert.match(await profile.innerText(),/Brain/);
  assert.match(await profile.innerText(),/Vision/);
  assert.match(await profile.innerText(),/No current FRIDAY duty/);
  assert.match(await profile.innerText(),/Provider health[\s\S]*Not reported/);
  await text('#fn-profile', /Background AI is unavailable/);
  assert.equal(await profile.locator('[data-serving]').count(),0);
  const avatar = await directory.locator('[data-entry="'+primary+'"] svg').innerHTML();
  await shot('07-roster-desktop');
  check('Shared catalog directory, persistent names/ID portraits and honest unsupported controls');

  await search.fill('fixture-fallback');
  assert.equal(await directory.locator('[data-entry]').count(),1);
  assert.equal(await directory.locator('[data-entry]').getAttribute('data-entry'),fallback);
  await search.fill('no-such-character');
  await text('#fn-person-list',/No entries match/);
  await search.fill('');
  await select(primary);
  await directory.locator('[data-entry="'+primary+'"]').press('End');
  const lastKey = await directory.locator('[data-entry]').last().getAttribute('data-entry');
  assert.equal(await directory.locator('[aria-pressed=true]').getAttribute('data-entry'),lastKey);
  assert.equal(await page.evaluate(()=>document.activeElement.dataset.entry),lastKey);
  assert.notEqual(await directory.locator('[data-entry="'+lastKey+'"]').evaluate(el=>getComputedStyle(el).outlineStyle),'none');
  await control('roster:split');
  await text('#fn-person-list',/FRIDAY/);
  await wait(key=>document.activeElement.dataset.entry===key,lastKey);
  await select(local);
  await text('#fn-profile',/excluded from bulk/);
  assert.ok(!requests.some(item=>/^lab_set|set_.*eligib|set_.*life/.test(item.method)));
  check('Search, empty search results, keyboard selection/focus and local exclusion without writes');

  await control('roster:split');
  await refresh();
  await select(primary);
  await text('#fn-current-duty',/FRIDAY · Vision/);
  assert.doesNotMatch(await page.locator('#fn-current-duty').innerText(),/Brain/);
  await select(fallback);
  await text('#fn-current-duty',/FRIDAY · Brain/);
  await shot('08-roster-split-duty');
  await control('roster:finish-brain');
  await refresh();
  await text('#fn-current-duty',/No current/);
  assert.doesNotMatch(await profile.innerText(),/No successful serving history/);
  await select(primary);
  await text('#fn-current-duty',/FRIDAY · Vision/);
  check('Brain failover leaves vision with the original character; current duty and successful history differ');

  await page.getByRole('button',{name:'Services',exact:true}).click();
  assert.equal(await directory.locator('[data-entry]').count(),3);
  await directory.locator('[data-entry]').first().click();
  await text('#fn-profile',/Procedural representation only/);
  assert.equal(await profile.locator('#fn-find-town').count(),0);
  await page.getByRole('button',{name:'History',exact:true}).click();
  await directory.locator('[data-entry="resident:research"]').click();
  await text('#fn-profile',/History remains with its original owner/);
  await directory.locator('[data-entry^="unresolved:"]').first().click();
  await text('#fn-profile',/historical ownership not established/);
  await control('roster:archive');
  await refresh();
  await select(primary);
  await text('#fn-profile',/ARCHIVED CHARACTER/);
  assert.ok(await profile.locator('#fn-find-town').isDisabled());
  await control('roster:restore');
  await refresh();
  await page.getByRole('button',{name:'Characters',exact:true}).click();
  await select(primary);
  assert.equal(await directory.locator('[aria-pressed=true]').getAttribute('data-entry'),primary);
  check('Procedural services, typed unresolved history and archived/reappearing identities stay distinct');

  const before = await rpc('get_identity_views', [primary]);
  await profile.locator('#fn-find-town').click();
  await wait(()=>document.querySelector('#view-lab').classList.contains('active'));
  const handoff = page.locator('#roster-town-handoff');
  assert.equal(await handoff.getAttribute('data-character-id'),primary);
  assert.equal(await handoff.getAttribute('data-catalog-revision'),String(before.catalog_revision));
  assert.match(await handoff.innerText(),/Proposed placement only/);
  const passed = requests.findLast(item=>item.method==='get_identity_views'&&item.args.length===2);
  assert.deepEqual(passed.args,[primary,before.catalog_revision]);
  await nav('view-roster');
  await text('#fn-profile',names[primary]);
  await control('roster:map-primary');
  await refresh();
  await text('#fn-profile',/Verified source resident/);
  await profile.locator('#fn-find-town').click();
  await text('#roster-town-handoff',/Verified source resident selected/);
  await text('#lab-inspector',/FRIDAY/);
  check('Town handoff confirms exact UUID/revision; proposed sprites are not called installed; verified legacy link is exact');

  await nav('view-roster');
  await page.setViewportSize({width:760,height:700});
  await select(primary);
  await shot('09-roster-compact');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.locator('#fn-profile-jump').click();
  assert.equal(await page.evaluate(()=>document.activeElement.id),'fn-profile');
  assert.ok(await profile.locator('h2').isVisible());
  await page.screenshot({path:require('node:path').join(__dirname,'screenshots/09b-roster-compact-profile.png')});
  await page.setViewportSize({width:390,height:844});
  await shot('10-roster-narrow');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.locator('#fn-profile-jump').click();
  await page.screenshot({path:require('node:path').join(__dirname,'screenshots/10b-roster-narrow-profile.png')});
  await page.setViewportSize({width:1440,height:930});
  await control('roster:disabled');
  await refresh();
  await text('#fn-roster-status',/Catalog reader is disabled/);
  await page.getByRole('button',{name:'History',exact:true}).click();
  await directory.locator('[data-entry="resident:friday"]').click();
  await text('#fn-profile',/ownership is unresolved/);
  assert.equal(await profile.locator('#fn-find-town').count(),0);
  await shot('11-roster-reader-unavailable');
  await control('roster:transport-error');
  await refresh();
  await text('#fn-roster-status',/could not be loaded/);
  await control('roster:transport-recover');
  await refresh();
  await text('#fn-roster-status',/Catalog reader is disabled/);
  await control('roster:enabled');
  await control('roster:empty');
  await refresh();
  await page.getByRole('button',{name:'Characters',exact:true}).click();
  await text('#fn-person-list',/No configured characters/);
  await control('roster:restore');
  await refresh();
  await select(primary);
  assert.equal(await directory.locator('[data-entry="'+primary+'"] svg').innerHTML(),avatar);
  await page.reload();
  await nav('view-roster');
  await text('#fn-roster-status',/Catalog revision/);
  await select(primary);
  assert.equal(await directory.locator('[data-entry="'+primary+'"] svg').innerHTML(),avatar);
  assert.match(await profile.innerText(),new RegExp(names[primary]));
  assert.deepEqual((await control('roster:read')).memories,fixture.memories);
  check('Compact/narrow layouts, disabled reader, transport failure/recovery, empty catalog and reload preserve identity/history');
};
