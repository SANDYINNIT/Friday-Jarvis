"""Deterministic rejection of Whisper hallucinations and empty speech.

Runs before any dispatch decision.  The genuine-empty case is already handled
by the caller; these filters cover the far more common failure mode where
Whisper synthesizes plausible-sounding boilerplate or repetition from near-
silence.  All rules are cheap, explicit, and never require a model call.
"""

import re
import unicodedata


HALLUCINATION_PATTERNS = (
    (r"subtitles?\s+by\s+(?:the\s+)?\w+", "captions boilerplate"),
    (r"\b(thanks|thank you)\s+for\s+(watching|viewing|listening|the\s+watch)\b", "sign-off greeting"),
    # ROUND ZB-L0 (2026-10-07): this was
    #   r"\b(please\s+)?(like|subscribe)|like and subscribe|subscription\b"
    # whose `(please\s+)?` group is OPTIONAL, so the first alternative collapsed
    # to matching the bare word "like" (or "subscribe") anywhere in speech.
    # Measured over 984 real STT transcripts from friday.log: 47 utterances were
    # rejected, all 47 by this rule, all 47 matched the bare word, and NONE was
    # a channel promo. Real casualties included "No, Friday. I was just like
    # working on this like weird Minecraft thing" and "i really like that, open
    # notepad". It now requires an actual promotional construction.
    (r"\b(like\s+(?:and\s+)?subscribe|please\s+subscribe|"
     r"smash\s+(?:that\s+|the\s+)?like|hit\s+the\s+like\s+button|"
     r"subscription(?:\s+link)?)\b", "channel promo"),
    (r"\b(what\s+up\s+guys|hey\s+guys|hello\s+everyone)\s+(welcome|thanks)", "channel intro"),
    (r"\b(welcome back|today.{0,40}going to talk about)\b", "channel intro"),
    (r"\b(sponsored|patreon|\bads\b)\s+by\b", "channel promo"),
    (r"\b(transcript provided|powered by|generated by)\b", "caption boilerplate"),
)

# ROUND ZB-L0 (2026-10-07): bracketed caption tokens like "[music]" used to be
# detected by the rule
#   r"\[?\b(music|applause|laughter|silence|foreign|noise|inaudible)\b\]?"
# whose brackets were OPTIONAL - and because _normalized() strips every
# non-word character, "[music]" and "play the music" become the identical
# string "music" by the time any rule runs. Matching the bare word therefore
# rejected ordinary speech ("play the music", "I heard a noise", "in silence
# mode") and could not be repaired by tightening that pattern. The bracketed
# form is unambiguous, so it is matched on the RAW text before normalization.
BRACKETED_CAPTION_RE = re.compile(
    r"\[\s*(?:music|applause|laughter|blip|silence|inaudible|noise|"
    r"foreign\s+language|audience\s+applause|upbeat\s+music)\s*\]",
    re.IGNORECASE,
)


def _normalized(text):
    text = unicodedata.normalize("NFKC", str(text or "")).casefold()
    text = re.sub(r"[^\w\s]", " ", text, flags=re.UNICODE)
    return " ".join(text.split())


def _repeat_ratio(text):
    words = re.findall(r"[\w]+", text)
    if len(words) < 4:
        return 0.0
    unique = set(words)
    return 1.0 - (len(unique) / len(words))


def reject_reason(text):
    """Return a human-readable reason for rejecting ``text``, or ``None``."""
    if not isinstance(text, str):
        return None
    # Bracketed caption tokens first: only the raw text still has the brackets.
    if BRACKETED_CAPTION_RE.search(text):
        return "background-caption token"
    normalized = _normalized(text)
    if not normalized:
        return "empty"
    for pattern, label in HALLUCINATION_PATTERNS:
        if re.search(pattern, normalized):
            return label
    if _repeat_ratio(normalized) > 0.6:
        return "repetitive no-speech sleep"
    return None